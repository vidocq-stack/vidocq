/**
 * VID-001 regression vehicle: a strictly named application module booting the
 * Vidocq runtime with the Cyrano wrapper on the module path. No {@code opens}
 * of its own — the bug surface is in the <em>wrapper</em> module.
 */
module io.vidocq.runtime.it.cyranojavamodule {
    requires jakarta.cdi;
    requires jakarta.inject;
    requires io.vidocq.runtime.core;
    requires io.vidocq.runtime.extensions.microprofile.cyrano;
    requires io.vidocq.vauban.api;

    exports io.vidocq.runtime.it.cyranojavamodule;

    // Generated by the processors: in-module instantiation and injection of this module's beans
    // (Vauban), and the proxy of GreetingClient (cyrano-processor, through the Rest Client codegen
    // bundle), so the module opens nothing. The test boots the runtime without the application
    // layer that `Vidocq.run` creates, so the module declares the providers itself.
    provides io.vidocq.vauban.api.VaubanComponentProvider
            with io.vidocq.runtime.it.cyranojavamodule._VaubanComponents;
    provides io.vidocq.cyrano.spi.gen.ClientProxyFactory
            with io.vidocq.runtime.it.cyranojavamodule.GreetingClient$$CyranoClient.Factory;
}
