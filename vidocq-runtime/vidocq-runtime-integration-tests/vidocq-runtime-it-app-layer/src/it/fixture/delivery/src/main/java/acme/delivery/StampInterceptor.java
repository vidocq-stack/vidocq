package acme.delivery;

import jakarta.annotation.Priority;
import jakarta.interceptor.AroundInvoke;
import jakarta.interceptor.Interceptor;
import jakarta.interceptor.InvocationContext;
import jakarta.ws.rs.core.Response;

/** Sets a header on the answer of a {@link Stamped} method: the client sees that the call was intercepted. */
@Stamped
@Interceptor
@Priority(Interceptor.Priority.APPLICATION)
public class StampInterceptor {

    /** The header the interceptor sets. */
    public static final String HEADER = "X-Acme-Stamped";

    @AroundInvoke
    Object stamp(InvocationContext context) throws Exception {
        Response response = (Response) context.proceed();
        return Response.fromResponse(response).header(HEADER, "yes").build();
    }
}
