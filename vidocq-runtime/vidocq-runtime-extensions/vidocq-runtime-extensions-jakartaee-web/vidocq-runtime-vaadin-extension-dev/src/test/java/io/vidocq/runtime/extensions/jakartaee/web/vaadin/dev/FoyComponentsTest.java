package io.vidocq.runtime.extensions.jakartaee.web.vaadin.dev;

import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

import static org.junit.jupiter.api.Assertions.assertNotNull;

/**
 * Foy creates the servlet of the event stream and its initializer through components generated at build: resolved
 * at start, they would go through reflection, with a warning at every start of {@code vidocq:dev}.
 */
class FoyComponentsTest {

    @ParameterizedTest
    @ValueSource(classes = {RedefinedEvents.class, RedefinedEvents.Initializer.class})
    void aWebComponentOfThisModuleHasItsFoyComponent(Class<?> type) throws ClassNotFoundException {
        assertNotNull(Class.forName(type.getName() + "$$FoyComponent", false, type.getClassLoader()));
    }
}
