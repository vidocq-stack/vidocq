package io.vidocq.runtime.spi.devconsole;

/** JSON text written by hand, for the bodies this module writes: it depends on no JSON library. */
final class JsonText {

    private JsonText() {
    }

    /** Appends {@code text} to {@code out} as a JSON string, its quotes, backslashes and control characters escaped. */
    static void quote(String text, StringBuilder out) {
        out.append('"');
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            switch (c) {
                case '"' -> out.append("\\\"");
                case '\\' -> out.append("\\\\");
                case '\n' -> out.append("\\n");
                case '\r' -> out.append("\\r");
                case '\t' -> out.append("\\t");
                default -> {
                    if (c < 0x20) {
                        out.append(String.format("\\u%04x", (int) c));
                    } else {
                        out.append(c);
                    }
                }
            }
        }
        out.append('"');
    }
}
