package io.vidocq.kerckhoffs.cdi;

import jakarta.enterprise.util.AnnotationLiteral;
import jakarta.inject.Qualifier;

import java.lang.annotation.Retention;
import java.lang.annotation.Target;

import static java.lang.annotation.ElementType.FIELD;
import static java.lang.annotation.ElementType.METHOD;
import static java.lang.annotation.ElementType.PARAMETER;
import static java.lang.annotation.ElementType.TYPE;
import static java.lang.annotation.RetentionPolicy.RUNTIME;

/** The qualifier an application gives to the second of its BASIC mechanisms. */
@Qualifier
@Retention(RUNTIME)
@Target({FIELD, METHOD, TYPE, PARAMETER})
public @interface SecondRealm {

    /** The instance to look the qualified mechanism up with. */
    final class Literal extends AnnotationLiteral<SecondRealm> implements SecondRealm {
        private static final long serialVersionUID = 1L;

        public static final Literal INSTANCE = new Literal();
    }
}
