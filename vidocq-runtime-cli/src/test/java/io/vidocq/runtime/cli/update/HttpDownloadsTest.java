package io.vidocq.runtime.cli.update;

import com.sun.net.httpserver.HttpServer;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

/** Against a real local HTTP server: the client's executor must actually run its tasks. */
class HttpDownloadsTest {

    private HttpServer server;
    private String base;

    @TempDir
    Path dir;

    @BeforeEach
    void start() throws IOException {
        server = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
        server.createContext("/meta.xml", exchange -> {
            byte[] body = "<metadata/>".getBytes(StandardCharsets.UTF_8);
            exchange.sendResponseHeaders(200, body.length);
            exchange.getResponseBody().write(body);
            exchange.close();
        });
        server.start();
        base = "http://127.0.0.1:" + server.getAddress().getPort();
    }

    @AfterEach
    void stop() {
        server.stop(0);
    }

    @Test
    void fetchesABody() {
        try (HttpDownloads http = new HttpDownloads()) {
            assertEquals(Optional.of("<metadata/>"), http.fetch(base + "/meta.xml"));
            assertEquals(Optional.empty(), http.fetch(base + "/missing"));
        }
    }

    @Test
    void downloadsToAFileAndRejectsAMissingOne() throws IOException {
        try (HttpDownloads http = new HttpDownloads()) {
            Path file = dir.resolve("meta.xml");
            http.download(base + "/meta.xml", file);
            assertEquals("<metadata/>", Files.readString(file));

            assertThrows(IOException.class, () -> http.download(base + "/missing", dir.resolve("x")));
        }
    }
}
