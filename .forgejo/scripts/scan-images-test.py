#!/usr/bin/env python3
"""Tests of scan-images.py, with a fake Trivy and a fake Docker: no network, no daemon.

    python3 -I .forgejo/scripts/scan-images-test.py
"""
import importlib.util
import json
import os
import pathlib
import sys
import tempfile
import unittest

sys.dont_write_bytecode = True  # no __pycache__ next to the scripts

HERE = pathlib.Path(__file__).resolve().parent
SPEC = importlib.util.spec_from_file_location("scan", HERE / "scan-images.py")
scan = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(scan)

WRAPPING = """# Generated by vidocq:docker
FROM gcr.io/distroless/base-debian12:nonroot

COPY dist /opt/app/
ENTRYPOINT ["/opt/app/bin/java", "-m", "app/app.Main"]
"""

LINKING = """FROM --platform=linux/amd64 eclipse-temurin:25-jdk AS link
COPY jlink-mods /build/mods
RUN jlink @/build/jlink.args --module-path /build/mods:${JAVA_HOME}/jmods --output /opt/app

FROM gcr.io/distroless/base-debian12:nonroot
COPY --from=link /opt/app /opt/app
"""


def vulnerability(identifier, package, severity, fixed=""):
    return {"VulnerabilityID": identifier, "PkgName": package, "InstalledVersion": "1.0",
            "FixedVersion": fixed, "Severity": severity, "Title": "title of " + identifier}


def trivy_answer(*results):
    return json.dumps({"SchemaVersion": 2, "Results": [
        {"Target": target, "Class": "os-pkgs", "Type": "debian", "Vulnerabilities": list(found)}
        for target, found in results]})


class BaseImage(unittest.TestCase):
    def test_the_only_stage(self):
        self.assertEqual("gcr.io/distroless/base-debian12:nonroot", scan.base_image(WRAPPING))

    def test_the_last_stage_of_a_linking_dockerfile(self):
        self.assertEqual("gcr.io/distroless/base-debian12:nonroot", scan.base_image(LINKING))

    def test_a_last_stage_built_on_an_earlier_one_names_that_one_base(self):
        text = "FROM --platform=linux/arm64 debian:12 AS base\nRUN true\nFROM base\nCOPY x /x\n"
        self.assertEqual("debian:12", scan.base_image(text))

    def test_no_from(self):
        self.assertIsNone(scan.base_image("# nothing\n"))


class Findings(unittest.TestCase):
    def test_counts_by_severity_and_keeps_the_high_and_critical_ones(self):
        answer = trivy_answer(
            ("img (debian 12.12)", [vulnerability("CVE-1", "libc6", "HIGH", "2.36-9+deb12u10"),
                                     vulnerability("CVE-2", "libssl3", "LOW"),
                                     vulnerability("CVE-3", "libssl3", "CRITICAL")]),
            ("opt/app/lib/x.jar", []))
        found = scan.findings(answer)
        self.assertEqual({"CRITICAL": 1, "HIGH": 1, "MEDIUM": 0, "LOW": 1, "UNKNOWN": 0}, found.counts)
        self.assertEqual(["CVE-3", "CVE-1"], [row["VulnerabilityID"] for row in found.serious])
        self.assertEqual(3, found.total)

    def test_the_same_vulnerability_in_two_targets_counts_once_per_package(self):
        answer = trivy_answer(("a", [vulnerability("CVE-1", "zlib", "HIGH")]),
                              ("b", [vulnerability("CVE-1", "zlib", "HIGH")]))
        self.assertEqual(1, scan.findings(answer).counts["HIGH"])

    def test_no_result_at_all(self):
        found = scan.findings(json.dumps({"SchemaVersion": 2}))
        self.assertEqual(0, found.total)
        self.assertEqual([], found.serious)


FAKE_TRIVY = """#!/usr/bin/env python3
import json, os, sys
args = sys.argv[1:]
with open(os.environ["FAKE_TRIVY_LOG"], "a") as log:
    log.write(json.dumps(args) + "\\n")
output = args[args.index("--output") + 1]
target = args[-1]
answers = json.loads(os.environ["FAKE_TRIVY_ANSWERS"])
if target not in answers:
    sys.exit(1)
with open(output, "w") as out:
    out.write(answers[target])
"""


class Scan(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = pathlib.Path(self.tmp.name)
        self.trivy = self.root / "trivy"
        self.trivy.write_text(FAKE_TRIVY)
        self.trivy.chmod(0o755)
        self.log = self.root / "trivy.log"
        self.work = self.root / "work"
        self.work.mkdir()
        os.environ["FAKE_TRIVY_LOG"] = str(self.log)

    def tearDown(self):
        os.environ.pop("FAKE_TRIVY_ANSWERS", None)
        os.environ.pop("FAKE_TRIVY_LOG", None)
        self.tmp.cleanup()

    def example(self, name, dockerfile=WRAPPING, dist=True, sbom=True):
        target = self.root / name / "target"
        target.mkdir(parents=True)
        if dist:
            (target / "dist" / "bin").mkdir(parents=True)
            if sbom:
                (target / "dist" / (name + "-0.5.0-cyclonedx.json")).write_text("{}")
        if dockerfile is not None:
            (target / "Dockerfile").write_text(dockerfile)
        return self.root / name

    def answers(self, answers):
        os.environ["FAKE_TRIVY_ANSWERS"] = json.dumps(answers)

    def calls(self):
        return [json.loads(line) for line in self.log.read_text().splitlines()]

    def test_without_docker_scans_the_jlink_image_and_the_base_image_from_its_registry(self):
        example = self.example("todo")
        self.answers({str(example / "target" / "dist" / "todo-0.5.0-cyclonedx.json"): trivy_answer(("Java", [])),
                      "gcr.io/distroless/base-debian12:nonroot":
                          trivy_answer(("base (debian 12)", [vulnerability("CVE-9", "libc6", "CRITICAL")]))})
        docker = scan.Docker(available=False)
        report = scan.scan([example], self.trivy, self.work, docker)
        sbom, image = self.calls()
        self.assertEqual("sbom", sbom[0])
        self.assertEqual(["image", "--image-src", "remote"], image[:3])
        self.assertIn("--scanners", sbom)
        self.assertEqual("vuln", sbom[sbom.index("--scanners") + 1])
        self.assertEqual(1, report.serious)
        self.assertIn("| todo | jlink image (its SBOM) | 0 | 0 | 0 | 0 |", report.markdown)
        self.assertIn("| todo | base image gcr.io/distroless/base-debian12:nonroot (registry, no Docker daemon) "
                      "| 1 | 0 | 0 | 0 |", report.markdown)
        self.assertIn("CVE-9", report.markdown)

    def test_a_jlink_image_without_an_sbom_is_scanned_as_a_file_system(self):
        example = self.example("todo", sbom=False)
        self.answers({str(example / "target" / "dist"): trivy_answer(),
                      "gcr.io/distroless/base-debian12:nonroot": trivy_answer()})
        report = scan.scan([example], self.trivy, self.work, scan.Docker(available=False))
        self.assertEqual("rootfs", self.calls()[0][0])
        self.assertIn("| todo | jlink image (rootfs) | 0 | 0 | 0 | 0 |", report.markdown)

    def test_with_docker_builds_the_image_and_scans_it(self):
        example = self.example("todo")
        self.answers({str(example / "target" / "dist" / "todo-0.5.0-cyclonedx.json"): trivy_answer(),
                      "vidocq-image-scan/todo:nightly": trivy_answer(("img", [vulnerability("CVE-5", "zlib", "HIGH")]))})
        built, removed = [], []
        docker = scan.Docker(available=True, build=lambda tag, target: built.append((tag, target)) or True,
                             remove=removed.append)
        report = scan.scan([example], self.trivy, self.work, docker)
        self.assertEqual([("vidocq-image-scan/todo:nightly", example / "target")], built)
        self.assertEqual(["vidocq-image-scan/todo:nightly"], removed)
        image = self.calls()[1]
        self.assertEqual(["image", "--image-src", "docker"], image[:3])
        self.assertIn("| todo | Docker image vidocq-image-scan/todo:nightly | 0 | 1 | 0 | 0 |", report.markdown)
        self.assertEqual(1, report.serious)

    def test_a_docker_build_that_fails_falls_back_to_the_base_image(self):
        example = self.example("todo")
        self.answers({str(example / "target" / "dist" / "todo-0.5.0-cyclonedx.json"): trivy_answer(),
                      "gcr.io/distroless/base-debian12:nonroot": trivy_answer()})
        docker = scan.Docker(available=True, build=lambda tag, target: False)
        report = scan.scan([example], self.trivy, self.work, docker)
        self.assertEqual(["image", "--image-src", "remote"], self.calls()[1][:3])
        self.assertIn("docker build failed", report.markdown)

    def test_an_example_without_an_image_is_reported_not_scanned(self):
        example = self.example("bare", dockerfile=None, dist=False)
        self.answers({})
        report = scan.scan([example], self.trivy, self.work, scan.Docker(available=False))
        self.assertFalse(self.log.exists())
        self.assertEqual(["bare: no jlink image in target/dist", "bare: no target/Dockerfile (its dist profile has no vidocq:docker)"], report.not_scanned)
        self.assertIn("bare: no jlink image in target/dist", report.markdown)

    def test_a_trivy_failure_is_reported_and_the_scan_goes_on(self):
        example = self.example("todo")
        self.answers({"gcr.io/distroless/base-debian12:nonroot": trivy_answer()})
        report = scan.scan([example], self.trivy, self.work, scan.Docker(available=False))
        self.assertEqual(2, len(self.calls()))
        self.assertEqual(["todo: Trivy failed on the jlink image (exit 1)"], report.not_scanned)

    def test_the_base_image_is_scanned_once_for_every_example(self):
        first, second = self.example("a"), self.example("b")
        self.answers({str(first / "target" / "dist" / "a-0.5.0-cyclonedx.json"): trivy_answer(),
                      str(second / "target" / "dist" / "b-0.5.0-cyclonedx.json"): trivy_answer(),
                      "gcr.io/distroless/base-debian12:nonroot":
                          trivy_answer(("base", [vulnerability("CVE-7", "libssl3", "HIGH")]))})
        report = scan.scan([first, second], self.trivy, self.work, scan.Docker(available=False))
        self.assertEqual(3, len(self.calls()))
        self.assertEqual(1, report.serious)  # one vulnerability, in the image of two examples
        self.assertIn("| b | base image gcr.io/distroless/base-debian12:nonroot", report.markdown)


class Annotations(unittest.TestCase):
    def test_report_mode_warns_of_serious_findings_and_of_what_was_not_scanned(self):
        self.assertEqual(["::warning::Image scan: 3 HIGH or CRITICAL vulnerabilities, see the job summary",
                          "::warning::Image scan: x"],
                         scan.annotations(scan.Report("", serious=3, not_scanned=["x"])))

    def test_nothing_to_say(self):
        self.assertEqual([], scan.annotations(scan.Report("", serious=0, not_scanned=[])))


if __name__ == "__main__":
    unittest.main()
