/**
 * Verify that every {@code vidocq-runtime-<name>-extension} declared in the project
 * dependencies has its companion {@code vidocq-runtime-<name>-extension-codegen} bundle
 * in the {@code maven-compiler-plugin}'s {@code <annotationProcessorPaths>}, and vice versa.
 *
 * <p>Four checks are performed:</p>
 * <ol>
 *   <li><b>Missing core codegen</b> — an extension is declared but {@code vidocq-runtime-core-codegen}, the
 *       Vauban indexer the parent wires, is absent from APT paths: an {@code <annotationProcessorPaths>}
 *       without {@code combine.children="append"} replaced it. Not checked under {@code <proc>none</proc>}.</li>
 *   <li><b>Missing codegen</b> — an extension is declared but its codegen bundle is absent
 *       from APT paths. The extension's {@code META-INF/vidocq/extension.properties} names the bundle, or
 *       says there is none (Vidocq/vidocq#314). For an extension without that descriptor, the bundle is the
 *       one its name gives by convention, and the codegen artifact must actually exist in any reachable
 *       repository for this to flag (so extensions that legitimately ship no codegen are silently ignored).</li>
 *   <li><b>Orphan codegen</b> — a codegen bundle is in APT paths but the matching extension
 *       is not in the dependency list. Usually a leftover after removing an extension.</li>
 *   <li><b>Version drift</b> — an extension and its codegen are declared with mismatching
 *       versions. Prevents the runtime adapter and the APT-generated bytecode from diverging
 *       across upgrades.</li>
 * </ol>
 *
 * <p>{@code vidocq-runtime-core-codegen} is treated as universal: it has no counterpart
 * runtime extension, so it never triggers an orphan or version-drift report.</p>
 *
 * <p>Default phase: {@code validate} — runs at the very start of every build so drift is
 * caught before any expensive work. Skipping with {@code -Dvidocq.checkpom.skip=true} or
 * downgrading failures to warnings with {@code -Dvidocq.checkpom.failOnMissing=false}.</p>
 */
@Mojo(name = "checkpom",
      defaultPhase = LifecyclePhase.VALIDATE,
      requiresDependencyResolution = ResolutionScope.NONE,
      threadSafe = true)
public class VidocqCheckPomMojo extends AbstractMojo {

    private static final String VIDOCQ_RUNTIME_GROUP = "io.vidocq.runtime";
    private static final String CORE_CODEGEN = "vidocq-runtime-core-codegen";
    private static final String MAVEN_JAR_KEY = "org.apache.maven.plugins:maven-jar-plugin";
    private static final String MAVEN_COMPILER_KEY = "org.apache.maven.plugins:maven-compiler-plugin";
    /** Matches a runtime extension artifact, e.g. {@code vidocq-runtime-cassini-rest-extension}. */
    private static final Pattern EXTENSION_PATTERN =
            Pattern.compile("^vidocq-runtime-(.+)-extension$");
    /** Matches a codegen bundle artifact, e.g. {@code vidocq-runtime-cassini-rest-extension-codegen}. */
    private static final Pattern CODEGEN_PATTERN =
            Pattern.compile("^vidocq-runtime-(.+)-extension-codegen$");

    @Parameter(defaultValue = "${project}", readonly = true, required = true)
    private MavenProject project;

    /** Skip the check entirely. */
    @Parameter(property = "vidocq.checkpom.skip", defaultValue = "false")
    private boolean skip;

    /**
     * If {@code true} (the default), a missing codegen / orphan codegen / version drift
     * makes the build fail. Set to {@code false} to downgrade to warnings.
     */
    @Parameter(property = "vidocq.checkpom.failOnMissing", defaultValue = "true")
    private boolean failOnMissing;

    @Parameter(defaultValue = "${repositorySystemSession}", readonly = true, required = true)
    private RepositorySystemSession repoSession;

    @Parameter(defaultValue = "${project.remoteProjectRepositories}", readonly = true)
    private List<RemoteRepository> remoteRepos;

    @Component
    private RepositorySystem repoSystem;

    /**
     * The dependencies on a dev-only jar declared in a scope other than {@code test}
     * (Vidocq/vidocq#143): the packaging goals drop them anyway, and vidocq:dev brings
     * them. A warning, never a failure.
     */
    static List<String> findDevOnlyDeclarations(List<Dependency> declared,
                                                Function<Dependency, Optional<Path>> jarOf) {
        List<String> issues = new ArrayList<>();
        for (Dependency d : declared) {
            if ("test".equals(d.getScope()) || !isVidocqRuntimeGroup(d.getGroupId())) {
                continue;
            }
            if (jarOf.apply(d).map(DevOnlyJars::isDevOnly).orElse(false)) {
                issues.add(DevOnlyJars.droppedWarning(d.getArtifactId()));
            }
        }
        return issues;
    }

    /**
     * What the dev services of the catalog extensions among {@code dependencies} lack (BUG-20261031-05, -06, -07): the
     * provider on {@code vidocqPlugin} (the effective one, a parent's dependencies included; {@code null} when the
     * project does not build with it), the test-scope pair a plain {@code mvn test} needs, the pool's driver. A
     * warning, never a failure: the application builds, and a URL of its own still gives it a database.
     */
    static List<String> findDevServiceGaps(List<Dependency> dependencies, Plugin vidocqPlugin) {
        List<String> ids = new ArrayList<>();
        Map<ExtensionCoordinate, String> scopes = new LinkedHashMap<>();
        for (Dependency d : dependencies) {
            ExtensionCoordinate coordinate = new ExtensionCoordinate(d.getGroupId(), d.getArtifactId());
            scopes.putIfAbsent(coordinate, d.getScope() == null || d.getScope().isBlank() ? "compile" : d.getScope());
            String id = KnownExtensions.idOf(coordinate);
            if (KnownExtensions.isKnown(id) && KnownExtensions.resolve(id).equals(coordinate)) {
                ids.add(id);
            }
        }
        List<ExtensionCoordinate> onPlugin = vidocqPlugin == null ? List.of() : vidocqPlugin.getDependencies().stream()
                .map(d -> new ExtensionCoordinate(d.getGroupId(), d.getArtifactId())).toList();
        return DevServiceWiring.missing(ids, new DevServiceWiring.Declared(onPlugin, scopes)).stream()
                .map(gap -> "Vidocq checkpom: " + gap + ". `vidocq doctor --fix` declares it, as `vidocq extension add`"
                        + " does.")
                .toList();
    }

    /**
     * Whether {@code project} builds a dev-only jar itself (a {@code -dev} companion, the console): its
     * maven-jar-plugin writes {@code Vidocq-Dev-Only: true} into the manifest. Such a module depends on dev tools by
     * design.
     */
    static boolean isDevOnlyProject(MavenProject project) {
        Plugin jar = project.getPlugin(MAVEN_JAR_KEY);
        if (jar == null) return false;
        return Stream.concat(
                        Stream.ofNullable(jar.getConfiguration()),
                        jar.getExecutions().stream().map(PluginExecution::getConfiguration))
                .filter(Xpp3Dom.class::isInstance)
                .map(Xpp3Dom.class::cast)
                .map(c -> c.getChild("archive"))
                .filter(Objects::nonNull)
                .map(a -> a.getChild("manifestEntries"))
                .filter(Objects::nonNull)
                .map(m -> m.getChild(DevOnlyJars.MANIFEST_ENTRY))
                .anyMatch(e -> e != null && "true".equalsIgnoreCase(e.getValue() == null ? "" : e.getValue().strip()));
    }

    /**
     * Resolve a dependency to its jar file. Returns {@link Optional#empty()} on any
     * resolution failure, so the calling code never crashes on unavailable artifacts.
     * Package-private: a test resolves every dependency to a jar of its own.
     */
    Optional<Path> resolvedJar(Dependency d) {
        if (d.getVersion() == null) return Optional.empty();
        try {
            ArtifactRequest req = new ArtifactRequest();
            req.setArtifact(new DefaultArtifact(d.getGroupId(), d.getArtifactId(), "jar",
                    d.getVersion()));
            req.setRepositories(remoteRepos);
            Artifact resolved = repoSystem.resolveArtifact(repoSession, req).getArtifact();
            return Optional.of(resolved.getFile().toPath());
        } catch (ArtifactResolutionException _) {
            return Optional.empty();
        }
    }

    @Override
    public void execute() throws MojoFailureException {
        if (skip) {
            getLog().info("Vidocq checkpom: skipped (-Dvidocq.checkpom.skip=true)");
            return;
        }

        // POM-only modules (reactor parents, codegen bundles) have no compile output
        // to protect — checking them produces noise without value.
        if ("pom".equals(project.getPackaging())) {
            getLog().debug("Vidocq checkpom: skipping POM-only module " + project.getArtifactId());
            return;
        }

        // Warned about first, whatever the checks below find: a warning, never a failure. A dev-only module
        // depends on dev tools by design.
        boolean devOnly = isDevOnlyProject(project);
        if (!devOnly) {
            for (String issue : findDevOnlyDeclarations(project.getDependencies(), this::resolvedJar)) {
                getLog().warn(issue);
            }
        }

        if (!devOnly) {
            Plugin vidocqPlugin = project.getPlugin(VIDOCQ_RUNTIME_GROUP + ":" + DevServiceWiring.PLUGIN.artifactId());
            findDevServiceGaps(project.getDependencies(), vidocqPlugin).forEach(getLog()::warn);
        }

        Map<String, String> extensionGroups = new LinkedHashMap<>();
        Map<String, String> extensions = collectExtensions(extensionGroups);
        Map<String, String> codegenPaths = collectCodegenPaths();
        // A warning, never a failure: Maven builds a pom-typed path, only IntelliJ's own build loses it (#237).
        for (String codegen : collectPomTypedCodegenPaths()) {
            getLog().warn("Vidocq checkpom: codegen bundle '" + codegen + "' is declared with <type>pom</type> in"
                    + " annotationProcessorPaths. Maven runs its processors, but IntelliJ's Maven import ignores a"
                    + " processor path of type pom, so IntelliJ's own build runs none of them (Vidocq/vidocq#237)."
                    + " Remove the <type>pom</type> line.");
        }

        // A module that has no extension in its deps and no codegen bundle beyond the
        // core-codegen inherited from the parent has nothing actionable to verify.
        boolean hasOnlyCoreCodegen = codegenPaths.size() == 1 && codegenPaths.containsKey(CORE_CODEGEN);
        if (extensions.isEmpty() && (codegenPaths.isEmpty() || hasOnlyCoreCodegen)) {
            getLog().debug("Vidocq checkpom: " + project.getArtifactId()
                    + " has no Vidocq extension/codegen coupling, nothing to check");
            return;
        }

        List<String> issues = new ArrayList<>();
        // A dev-only module (a -dev companion) reads its runtime extension's live API and generates nothing: its
        // extension needs no codegen bundle there (#147). Orphans and drifts are still checked.
        if (!devOnly) {
            findMissingCoreCodegen(extensions, codegenPaths).ifPresent(issues::add);
            issues.addAll(findMissingCodegens(extensions, extensionGroups, codegenPaths));
        }
        issues.addAll(findOrphanCodegens(extensions, codegenPaths));
        issues.addAll(findVersionDrifts(extensions, codegenPaths));

        if (issues.isEmpty()) {
            getLog().info("Vidocq checkpom: " + extensions.size() + " extension(s) and "
                    + codegenPaths.size() + " codegen path(s) — all aligned.");
            return;
        }

        reportIssues(issues);
    }

    /** Logs {@code issues} as errors and fails the build when {@code failOnMissing}, else as warnings. */
    private void reportIssues(List<String> issues) throws MojoFailureException {
        for (String issue : issues) {
            if (failOnMissing) getLog().error(issue);
            else getLog().warn(issue);
        }
        if (failOnMissing) {
            throw new MojoFailureException("Vidocq checkpom found " + issues.size()
                    + " issue(s). Fix them or downgrade to warnings via -Dvidocq.checkpom.failOnMissing=false.");
        }
    }

    // ---- Check 0: Extension declared, core codegen missing ----

    /**
     * The parent wires {@code vidocq-runtime-core-codegen}, the Vauban indexer; an application's
     * {@code <annotationProcessorPaths>} without {@code combine.children="append"} replaces that entry, and the
     * application's beans get no generated factory (BUG-20261023-02). A module running no processor is left alone.
     */
    private Optional<String> findMissingCoreCodegen(Map<String, String> extensions,
                                                    Map<String, String> codegenPaths) {
        if (extensions.isEmpty() || codegenPaths.containsKey(CORE_CODEGEN) || annotationProcessingDisabled()) {
            return Optional.empty();
        }
        return Optional.of("'" + CORE_CODEGEN + "' (the Vauban indexer) is missing from"
                + " maven-compiler-plugin/annotationProcessorPaths, so the application's beans get no generated"
                + " factory. The vidocq-runtime-parent declares it: an <annotationProcessorPaths> without"
                + " combine.children=\"append\" replaces that entry. Declare"
                + " <annotationProcessorPaths combine.children=\"append\">, or add it yourself:\n"
                + "<path>\n"
                + "    <groupId>" + VIDOCQ_RUNTIME_GROUP + "</groupId>\n"
                + "    <artifactId>" + CORE_CODEGEN + "</artifactId>\n"
                + "</path>");
    }

    private boolean annotationProcessingDisabled() {
        Plugin compiler = project.getPlugin(MAVEN_COMPILER_KEY);
        if (compiler == null || !(compiler.getConfiguration() instanceof Xpp3Dom configuration)) return false;
        Xpp3Dom proc = configuration.getChild("proc");
        return proc != null && proc.getValue() != null && "none".equals(proc.getValue().strip());
    }

    // ---- Check 1: Extension declared, codegen missing ----

    private List<String> findMissingCodegens(Map<String, String> extensions,
                                             Map<String, String> extensionGroups,
                                             Map<String, String> codegenPaths) {
        List<String> result = new ArrayList<>();
        for (Map.Entry<String, String> ext : extensions.entrySet()) {
            String extName = ext.getKey();
            String extVer = ext.getValue();
            Optional<String> codegen = expectedCodegen(extName, extensionGroups.get(extName), extVer);
            if (codegen.isEmpty() || codegenPaths.containsKey(codegen.get())) continue;
            String codegenName = codegen.get();

            // What a missing bundle costs depends on the extension — a failed compilation for Ravel,
            // a reflective fallback for Cassini — and the bundle's own description says it. The
            // message gives what every case needs: the entry to add (ravel#21).
            result.add("Vidocq extension '" + extName + "' is declared but its codegen bundle '"
                    + codegenName + "' is missing from maven-compiler-plugin/annotationProcessorPaths,"
                    + " so the extension's compile-time processing does not run. Add it inside"
                    + " <annotationProcessorPaths combine.children=\"append\">:\n"
                    + "<path>\n"
                    + "    <groupId>" + extensionGroups.get(extName) + "</groupId>\n"
                    + "    <artifactId>" + codegenName + "</artifactId>\n"
                    + "    <version>" + extVer + "</version>\n"
                    + "</path>");
        }
        return result;
    }

    /**
     * The codegen bundle {@code extName} needs, under its group: the one its {@link ExtensionDescriptor} names
     * (Vidocq/vidocq#314), none if the descriptor names none. An extension without a descriptor, such as a
     * third-party one, needs the bundle its name gives by convention, when one is published.
     */
    private Optional<String> expectedCodegen(String extName, String groupId, String version) {
        Dependency extension = new Dependency();
        extension.setGroupId(groupId);
        extension.setArtifactId(extName);
        extension.setVersion(version);
        Optional<ExtensionDescriptor> descriptor = resolvedJar(extension).flatMap(ExtensionDescriptor::of);
        if (descriptor.isPresent()) {
            return descriptor.get().codegen();
        }
        Matcher m = EXTENSION_PATTERN.matcher(extName);
        if (!m.matches()) return Optional.empty();
        String byConvention = extensionArtifact(m.group(1)) + "-codegen";
        // The codegen bundle lives under the same group as its runtime extension, so resolve it there.
        if (codegenArtifactExists(byConvention, groupId, version)) {
            return Optional.of(byConvention);
        }
        getLog().debug("Vidocq checkpom: '" + extName + "' has no companion codegen artifact, skipping.");
        return Optional.empty();
    }

    /** The artifactId of the runtime extension {@code name}, e.g. {@code vidocq-runtime-cassini-rest-extension}. */
    private static String extensionArtifact(String name) {
        return "vidocq-runtime-" + name + "-extension";
    }

    // ---- Check 2: Codegen path declared, no matching extension ----

    private List<String> findOrphanCodegens(Map<String, String> extensions,
                                            Map<String, String> codegenPaths) {
        List<String> result = new ArrayList<>();
        for (String codegenName : codegenPaths.keySet()) {
            String extName = extensionOf(codegenName);
            if (extName != null && !extensions.containsKey(extName)) {
                result.add("Codegen bundle '" + codegenName + "' is in annotationProcessorPaths "
                        + "but its runtime extension '" + extName + "' is not declared as a "
                        + "dependency. Remove the orphan codegen path or add the extension.");
            }
        }
        return result;
    }

    /**
     * The runtime extension artifact a codegen bundle belongs to, or {@code null} for the core codegen, which is
     * universal, and for a name that is not a codegen bundle's.
     */
    private static String extensionOf(String codegenName) {
        if (CORE_CODEGEN.equals(codegenName)) {
            return null;
        }
        Matcher m = CODEGEN_PATTERN.matcher(codegenName);
        return m.matches() ? extensionArtifact(m.group(1)) : null;
    }

    // ---- Check 3: Extension and codegen at different versions ----

    private List<String> findVersionDrifts(Map<String, String> extensions,
                                           Map<String, String> codegenPaths) {
        List<String> result = new ArrayList<>();
        for (Map.Entry<String, String> codegen : codegenPaths.entrySet()) {
            String codegenName = codegen.getKey();
            String codegenVer = codegen.getValue();
            String extName = extensionOf(codegenName);
            String extVer = extName == null ? null : extensions.get(extName);
            if (extVer != null && codegenVer != null && !Objects.equals(extVer, codegenVer)) {
                result.add("Version mismatch: '" + extName + "' is at " + extVer
                        + " but '" + codegenName + "' is at " + codegenVer
                        + ". Align both to the same version.");
            }
        }
        return result;
    }

    // ---- Extraction helpers ----

    /**
     * Vidocq runtime extensions and their codegen bundles live either under the legacy
     * {@code io.vidocq.runtime} group or under any {@code io.vidocq.runtime.extensions.*}
     * sub-group introduced by the domain-based reorganization (essentials, jakartaee.core,
     * jakartaee.web, microprofile, module.repackaged). Recognise the whole family.
     */
    static boolean isVidocqRuntimeGroup(String groupId) {
        return groupId != null
                && (groupId.equals(VIDOCQ_RUNTIME_GROUP) || groupId.startsWith(VIDOCQ_RUNTIME_GROUP + "."));
    }

    Map<String, String> collectExtensions(Map<String, String> groupsOut) {
        Map<String, String> result = new LinkedHashMap<>();
        for (Dependency d : project.getDependencies()) {
            String aid = d.getArtifactId();
            if (isVidocqRuntimeGroup(d.getGroupId()) && isExtensionArtifact(aid)) {
                result.put(aid, d.getVersion());
                groupsOut.put(aid, d.getGroupId());
            }
        }
        return result;
    }

    /** Whether {@code aid} names a runtime extension, its codegen bundle excepted. */
    private static boolean isExtensionArtifact(String aid) {
        // -codegen also contains "-extension-" — exclude explicitly.
        return !CODEGEN_PATTERN.matcher(aid).matches() && EXTENSION_PATTERN.matcher(aid).matches();
    }

    /** The Vidocq codegen bundles declared on the processor path with {@code <type>pom</type>}, in order. */
    private List<String> collectPomTypedCodegenPaths() {
        List<String> result = new ArrayList<>();
        for (ProcessorPath path : codegenPathElements()) {
            String aid = path.artifactId();
            if ("pom".equals(path.type()) && aid.endsWith("-codegen") && !result.contains(aid)) {
                result.add(aid);
            }
        }
        return result;
    }

    /** Every {@code <path>} of a Vidocq runtime group, from the plugin configuration and its executions. */
    private List<ProcessorPath> codegenPathElements() {
        return ProcessorPaths.of(project).stream().filter(p -> isVidocqRuntimeGroup(p.groupId())).toList();
    }

    private Map<String, String> collectCodegenPaths() {
        Map<String, String> result = new LinkedHashMap<>();
        for (ProcessorPath path : codegenPathElements()) {
            result.putIfAbsent(path.artifactId(), path.version());
        }
        return result;
    }

    // package-private: a test overrides it rather than resolve artifacts.
    boolean codegenArtifactExists(String artifactId, String groupId, String version) {
        if (version == null) version = project.getVersion();
        if (groupId == null) groupId = VIDOCQ_RUNTIME_GROUP;
        try {
            ArtifactRequest req = new ArtifactRequest();
            req.setArtifact(new DefaultArtifact(groupId, artifactId, "pom", version));
            req.setRepositories(remoteRepos);
            repoSystem.resolveArtifact(repoSession, req);
            return true;
        } catch (ArtifactResolutionException _) {
            return false;
        }
    }
}
