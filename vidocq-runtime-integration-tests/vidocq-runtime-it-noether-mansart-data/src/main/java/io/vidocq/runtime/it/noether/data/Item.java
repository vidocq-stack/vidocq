package io.vidocq.runtime.it.noether.data;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * One entity for both: the persistence unit and the repository map the same table. The names are explicit and upper
 * case, so the two mappings name the same table and columns whatever each one's naming rule is.
 */
@Entity
@Table(name = "ITEM")
public class Item {

    @Id
    @Column(name = "ID")
    private String id;

    @Column(name = "LABEL")
    private String label;

    public Item() {
    }

    public Item(String id, String label) {
        this.id = id;
        this.label = label;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getLabel() {
        return label;
    }

    public void setLabel(String label) {
        this.label = label;
    }
}
