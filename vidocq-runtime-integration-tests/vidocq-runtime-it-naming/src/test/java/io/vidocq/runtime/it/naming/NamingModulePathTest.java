package io.vidocq.runtime.it.naming;

import io.vidocq.runtime.core.VidocqBootstrap;
import jakarta.enterprise.inject.literal.NamedLiteral;
import jakarta.enterprise.inject.spi.CDI;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import javax.naming.Context;
import javax.naming.InitialContext;
import javax.naming.NamingException;
import javax.sql.DataSource;
import java.sql.SQLException;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertSame;

/**
 * vidocq#297: the assembled runtime, on the module path, with the naming extension. The {@code java:} names
 * are answered by the running container, and Mansart Data resolves a repository's JNDI data store through them.
 */
class NamingModulePathTest {

    private static VidocqBootstrap bootstrap;

    @BeforeAll
    static void boot() throws Exception {
        bootstrap = VidocqBootstrap.create().configure().start();
        var audit = (DataSource) new InitialContext().lookup("java:comp/env/jdbc/audit");
        try (var connection = audit.getConnection(); var statement = connection.createStatement()) {
            statement.execute("DROP TABLE IF EXISTS \"audit_log\"");
            statement.execute("CREATE TABLE \"audit_log\" ("
                    + "\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "\"action\" VARCHAR(500) NOT NULL)");
        }
    }

    @AfterAll
    static void shutdown() {
        if (bootstrap != null) {
            bootstrap.shutdown();
        }
    }

    private static DataSource auditBean() {
        return CDI.current().select(DataSource.class, NamedLiteral.of("audit")).get();
    }

    @Test
    void a_jdbc_name_is_the_named_pool_of_the_running_container() throws NamingException {
        assertSame(auditBean(), new InitialContext().lookup("java:comp/env/jdbc/audit"));
    }

    @Test
    void the_environment_context_resolves_a_relative_name() throws NamingException {
        var environment = (Context) new InitialContext().lookup("java:comp/env");

        assertSame(auditBean(), environment.lookup("jdbc/audit"));
    }

    @Test
    void a_repository_whose_data_store_is_a_java_name_writes_to_that_pool() throws SQLException {
        var journal = CDI.current().select(AuditJournal.class).get();

        journal.save(new AuditEntry("looked up through java:comp/env"));

        try (var connection = auditBean().getConnection();
             var statement = connection.createStatement();
             var rows = statement.executeQuery("SELECT COUNT(*) FROM \"audit_log\"")) {
            rows.next();
            assertEquals(1, rows.getLong(1), "the row is in the audit database");
        }
        assertEquals(1, journal.count());
    }
}
