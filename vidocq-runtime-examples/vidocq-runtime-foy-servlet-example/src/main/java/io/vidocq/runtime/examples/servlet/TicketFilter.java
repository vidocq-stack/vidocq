package io.vidocq.runtime.examples.servlet;

import jakarta.inject.Inject;
import jakarta.servlet.FilterChain;
import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebFilter;
import jakarta.servlet.http.HttpFilter;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

import java.io.IOException;

/** Stamps every response with the request ticket, which the page footer shows too. */
@WebFilter("/*")
public class TicketFilter extends HttpFilter {

    @Inject
    RequestTicket ticket;

    @Override
    protected void doFilter(HttpServletRequest req, HttpServletResponse resp, FilterChain chain)
            throws IOException, ServletException {
        resp.setHeader("X-Request-Id", ticket.id());
        resp.setHeader("X-Powered-By", "Vidocq (Foy on Chappe)");
        chain.doFilter(req, resp);
    }
}
