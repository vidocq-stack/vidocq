package io.vidocq.runtime.examples.mansart;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.context.Initialized;
import jakarta.enterprise.event.Observes;
import jakarta.inject.Inject;
import jakarta.inject.Named;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Demo-only bootstrap schema for the named {@code "audit"} datasource.
 *
 * <p>The {@code @Default} datasource (products table) is now migrated by the
 * {@code vidocq-runtime-flyway-migration-extension} via {@code db/migration/V1__products.sql} —
 * no manual DDL needed here.
 *
 * <p>The {@code @Observes @Initialized(ApplicationScoped.class)} trigger fires when the Vauban
 * CDI container is fully started, after the {@link DataSource} beans are available.
 * {@code @ApplicationScoped} beans are otherwise lazy in Vauban — without the observer, this
 * bean would never be instantiated.
 */
@ApplicationScoped
public class SchemaInitializer {

    // The "audit" datasource IS visible at compile time: its @Named("audit") holder is generated
    // into this module by mansart-pool-datasources-codegen, so it can be injected directly.
    // Named-DS migration is opt-in and out of scope here — the audit schema is initialised manually.
    @Inject
    @Named("audit")
    DataSource auditDataSource;

    void onStart(@Observes @Initialized(ApplicationScoped.class) Object event) {
        initSchema();
    }

    void initSchema() {
        // The "audit" table lives in a DISTINCT H2 database, reached through the @Named("audit")
        // DataSource above — proof that the named datasource is wired and independent of @Default.
        try (Connection c = auditDataSource.getConnection(); Statement s = c.createStatement()) {
            s.execute("DROP TABLE IF EXISTS \"audit_log\"");
            s.execute("CREATE TABLE \"audit_log\" ("
                    + "  \"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + "  \"action\" VARCHAR(500) NOT NULL"
                    + ")");
        } catch (SQLException e) {
            throw new IllegalStateException("Failed to initialize H2 audit schema", e);
        }
    }
}
