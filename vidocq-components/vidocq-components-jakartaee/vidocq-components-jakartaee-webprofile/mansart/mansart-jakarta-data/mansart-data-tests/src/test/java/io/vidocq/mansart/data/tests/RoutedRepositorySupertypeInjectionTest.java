package io.vidocq.mansart.data.tests;

import io.vidocq.vauban.core.container.VaubanContainer;
import io.vidocq.vauban.core.container.VaubanContainerBuilder;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * MANSART-068: a repository on a named data store is a synthetic bean, whose only bean type was the repository
 * interface. A bean that injected it by its parameterized supertype, {@code BasicRepository<RoutedNote, Long>},
 * stopped the container start, while the same injection of a repository on the default data store worked.
 */
class RoutedRepositorySupertypeInjectionTest {

    @BeforeAll
    static void createSchemas() throws Exception {
        for (String url : new String[]{RoutingDataSources.DEFAULT_URL, RoutingDataSources.AUDIT_URL}) {
            try (Connection c = RoutingDataSources.h2(url).getConnection(); Statement s = c.createStatement()) {
                s.execute("CREATE TABLE IF NOT EXISTS routed_notes ("
                        + "  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + "  text VARCHAR(200) NOT NULL"
                        + ")");
                s.execute("CREATE TABLE IF NOT EXISTS authors ("
                        + "  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + "  name VARCHAR(200) NOT NULL"
                        + ")");
            }
        }
    }

    private static VaubanContainerBuilder deployment() {
        return VaubanContainer.builder()
                .addBeanClass(io.vidocq.mansart.data.cdi.MansartDataExtension.class)
                .addBeanClass(io.vidocq.mansart.data.cdi.MansartRuntimeProducer.class)
                .addBeanClass(RoutingDataSources.class)
                .addBeanClass(RoutedNote.class);
    }

    private static int count(String url, String table, String column, String value) throws Exception {
        try (Connection c = RoutingDataSources.h2(url).getConnection(); Statement s = c.createStatement();
             ResultSet rows = s.executeQuery(
                     "SELECT COUNT(*) FROM " + table + " WHERE " + column + " = '" + value + "'")) {
            rows.next();
            return rows.getInt(1);
        }
    }

    @Test
    void aRoutedRepositoryIsInjectedByItsParameterizedSupertype() throws Exception {
        try (VaubanContainer container = deployment()
                .addBeanClass(RoutedNoteRepository.class)
                .addBeanClass(RoutedNoteRepositoryImpl.class)
                .addBeanClass(RoutedNoteDesk.class)
                .build()) {
            RoutedNote filed = container.select(RoutedNoteDesk.class).file("filed by the desk");

            assertThat(filed.getId()).isNotNull();
        }
        assertThat(count(RoutingDataSources.AUDIT_URL, "routed_notes", "text", "filed by the desk"))
                .as("the row is in the named data store").isEqualTo(1);
        assertThat(count(RoutingDataSources.DEFAULT_URL, "routed_notes", "text", "filed by the desk")).isZero();
    }

    /** {@code BasicRepository<ArchivedNote, Long>} is two levels up, through the type variables of CrudRepository. */
    @Test
    void aSupertypeReachedThroughTypeVariablesIsABeanTypeToo() {
        try (VaubanContainer container = deployment()
                .addBeanClass(ArchivedNote.class)
                .addBeanClass(RoutedNoteArchive.class)
                .addBeanClass(RoutedNoteArchiveImpl.class)
                .addBeanClass(RoutedNoteArchiveDesk.class)
                .build()) {
            RoutedNoteArchiveDesk desk = container.select(RoutedNoteArchiveDesk.class);
            RoutedNoteArchive archive = container.select(RoutedNoteArchive.class);

            assertThat(desk.crud()).isSameAs(archive);
            assertThat(desk.basic()).isSameAs(archive);
            assertThat(archive.label()).isEqualTo("archive");
        }
    }

    /** The default data store's repository is a class bean, the routed one a synthetic bean: each has one bean. */
    @Test
    void aRoutedAndADefaultRepositoryAreInjectedSideBySideWithoutAmbiguity() throws Exception {
        try (VaubanContainer container = deployment()
                .addBeanClass(RoutedNoteRepository.class)
                .addBeanClass(RoutedNoteRepositoryImpl.class)
                .addBeanClass(RoutedNoteDesk.class)
                .addBeanClass(Author.class)
                .addBeanClass(AuthorRepository.class)
                .addBeanClass(AuthorRepositoryImpl.class)
                .addBeanClass(AuthorDesk.class)
                .build()) {
            container.select(AuthorDesk.class).register("Marguerite Yourcenar");
            container.select(RoutedNoteDesk.class).file("filed next to an author");
        }
        assertThat(count(RoutingDataSources.DEFAULT_URL, "authors", "name", "Marguerite Yourcenar")).isEqualTo(1);
        assertThat(count(RoutingDataSources.AUDIT_URL, "authors", "name", "Marguerite Yourcenar")).isZero();
        assertThat(count(RoutingDataSources.AUDIT_URL, "routed_notes", "text", "filed next to an author"))
                .isEqualTo(1);
    }
}
