package io.vidocq.mansart.data.tests;

import io.vidocq.mansart.data.core.MansartData;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * MANSART-067: a mapped table or column name follows Jakarta Persistence. Written without quotes it reaches the
 * database undelimited, so the database folds it as it folds the names of an unquoted migration; written with
 * double quotes it is delimited and kept as it is. A repository and a persistence unit that share an entity then
 * name the same table.
 */
class MappedNameQuotingTest {

    private static JdbcDataSource database(String db, String... ddl) throws Exception {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:" + db + ";DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        try (Connection c = ds.getConnection(); Statement s = c.createStatement()) {
            for (String statement : ddl) {
                s.execute(statement);
            }
        }
        return ds;
    }

    @Test
    void aNameWithoutQuotesMatchesTheTableOfAnUnquotedMigrationWhateverItsCase() throws Exception {
        JdbcDataSource ds = database("mansart-067-mixed",
                "CREATE TABLE mixed_items (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + " item_label VARCHAR(200) NOT NULL)");
        MixedCaseItems items = MansartData.builder().dataSource(ds).build().repository(MixedCaseItems.class);

        MixedCaseItem item = new MixedCaseItem();
        item.setLabel("anvil");
        MixedCaseItem saved = items.save(item);

        assertThat(items.findById(saved.getId())).hasValueSatisfying(i -> assertThat(i.getLabel()).isEqualTo("anvil"));
        assertThat(items.findByLabel("anvil")).hasSize(1);
        saved.setLabel("hammer");
        items.save(saved);
        assertThat(items.findByLabel("hammer")).hasSize(1);
        items.deleteById(saved.getId());
        assertThat(items.findAll()).isEmpty();
    }

    @Test
    void aNameWrittenWithQuotesIsDelimited() throws Exception {
        JdbcDataSource ds = database("mansart-067-delimited",
                "CREATE TABLE \"Delimited Items\" (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        + " \"Item Label\" VARCHAR(200) NOT NULL)");
        DelimitedItems items = MansartData.builder().dataSource(ds).build().repository(DelimitedItems.class);

        DelimitedItem item = new DelimitedItem();
        item.setLabel("anvil");
        DelimitedItem saved = items.save(item);

        assertThat(items.findByLabel("anvil")).hasSize(1);
        saved.setLabel("hammer");
        items.save(saved);
        try (Connection c = ds.getConnection(); Statement s = c.createStatement();
             ResultSet rs = s.executeQuery("SELECT \"Item Label\" FROM \"Delimited Items\"")) {
            assertThat(rs.next()).isTrue();
            assertThat(rs.getString(1)).isEqualTo("hammer");
        }
        items.deleteById(saved.getId());
        assertThat(items.findAll()).isEmpty();
    }
}
