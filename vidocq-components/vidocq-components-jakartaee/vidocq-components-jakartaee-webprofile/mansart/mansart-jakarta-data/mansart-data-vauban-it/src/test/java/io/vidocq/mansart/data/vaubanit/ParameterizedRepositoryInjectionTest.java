package io.vidocq.mansart.data.vaubanit;

import io.vidocq.vauban.core.container.VaubanContainer;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Two repositories extend {@code BasicRepository} with different type arguments, and a bean injects each by that
 * parameterized supertype. The module is compiled by Mansart's processor and by Vauban's, as a Vidocq application
 * is, and started as one: from the beans the build indexed.
 *
 * <p>Two checks, at two moments. At build, the module's compilation fails on a warning (see its {@code pom.xml}):
 * Vauban's processor must see that {@code BooksImpl implements Books extends BasicRepository<Book, Long>}, although
 * {@code Books} is compiled by the same compilation, and resolve the two injection points instead of deferring them
 * to the runtime (Vauban BUG-20261117-03). At start, these tests: the container computes the bean types of the two
 * implementations again, and each injection point gets its repository.
 */
class ParameterizedRepositoryInjectionTest {

    private VaubanContainer container;

    @BeforeEach
    void createTablesAndBoot() throws SQLException {
        try (Connection c = DriverManager.getConnection(Stores.URL); Statement s = c.createStatement()) {
            s.execute("DROP TABLE IF EXISTS vit_books");
            s.execute("DROP TABLE IF EXISTS vit_authors");
            s.execute("CREATE TABLE vit_books (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " title VARCHAR(200) NOT NULL)");
            s.execute("CREATE TABLE vit_authors (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " name VARCHAR(200) NOT NULL)");
        }
        // As a Vidocq application starts: the beans are those the build indexed (META-INF/vauban-beans.list), so
        // BooksImpl and AuthorsImpl are class beans, with the bean types of their supertypes.
        container = VaubanContainer.builder().scanClasspath().build();
    }

    @AfterEach
    void close() {
        if (container != null) {
            container.close();
        }
    }

    @Test
    void aBasicRepositoryOfBookIsTheBookRepository() {
        Shelf shelf = container.select(Shelf.class);

        assertThat(shelf.books()).isInstanceOf(Books.class);
        Book book = new Book();
        book.setTitle("Les Misérables");
        Book saved = shelf.books().save(book);
        assertThat(container.select(Books.class).findById(saved.getId()))
                .hasValueSatisfying(found -> assertThat(found.getTitle()).isEqualTo("Les Misérables"));
    }

    @Test
    void aBasicRepositoryOfAuthorIsTheAuthorRepository() {
        Shelf shelf = container.select(Shelf.class);

        assertThat(shelf.authors()).isInstanceOf(Authors.class);
        Author author = new Author();
        author.setName("Victor Hugo");
        Author saved = shelf.authors().save(author);
        assertThat(container.select(Authors.class).findById(saved.getId()))
                .hasValueSatisfying(found -> assertThat(found.getName()).isEqualTo("Victor Hugo"));
    }
}
