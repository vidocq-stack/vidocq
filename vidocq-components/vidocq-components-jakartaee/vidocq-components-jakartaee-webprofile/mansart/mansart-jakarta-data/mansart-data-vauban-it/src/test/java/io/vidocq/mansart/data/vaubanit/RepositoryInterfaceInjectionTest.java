package io.vidocq.mansart.data.vaubanit;

import io.vidocq.mansart.data.cdi.MansartDataExtension;
import io.vidocq.mansart.data.cdi.MansartRuntimeProducer;
import io.vidocq.vauban.core.container.VaubanContainer;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * The control of {@link ParameterizedRepositoryInjectionTest}: the same module, but the bean injects {@link Books}
 * and {@link Authors} by their own interface, and the container is given its bean classes one by one. The generated
 * implementations are then not class beans: Mansart's extension registers each repository as a synthetic bean of
 * its interface alone, which is enough here and would not serve a {@code BasicRepository<Book, Long>} injection
 * point.
 */
class RepositoryInterfaceInjectionTest {

    @Test
    void repositoriesInjectedByTheirInterfaceWork() throws SQLException {
        try (Connection c = DriverManager.getConnection(Stores.URL); Statement s = c.createStatement()) {
            s.execute("DROP TABLE IF EXISTS \"vit_books\"");
            s.execute("CREATE TABLE \"vit_books\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " \"title\" VARCHAR(200) NOT NULL)");
        }
        try (VaubanContainer container = VaubanContainer.builder()
                .addBeanClass(MansartDataExtension.class)
                .addBeanClass(MansartRuntimeProducer.class)
                .addBeanClass(Stores.class)
                .addBeanClass(Books.class)
                .addBeanClass(Authors.class)
                .addBeanClass(Catalog.class)
                .build()) {
            Catalog catalog = container.select(Catalog.class);

            assertThat(catalog.authors()).isNotNull();
            Book book = new Book();
            book.setTitle("Notre-Dame de Paris");
            Book saved = catalog.books().save(book);
            assertThat(catalog.books().findById(saved.getId()))
                    .hasValueSatisfying(found -> assertThat(found.getTitle()).isEqualTo("Notre-Dame de Paris"));
        }
    }
}
